const r1 = (v: number) => Math.round(v * 10) / 10;
const list = Object.entries(out).flatMap(([town, es]) => es.map((e, i) => ({ id: NAMES[town][i][0], name: NAMES[town][i][1], town, door: e.lots[0].door,
  lane: e.lane.map(([x, z]) => [r1(x), r1(z)]), track: e.track.map(([x, z]) => [r1(x), r1(z)]), lots: e.lots.map((l) => [l.x0, l.z0, l.base]) })));
