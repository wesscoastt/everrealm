// Finds a coaching yard for every Charter Post stop on the roads (data/postYards.ts): flat ground beside
// the stop, facing it, off the road and clear of everything built. Run with `npm run -s poststations`.
import { writeFileSync } from 'node:fs';
import { yardAt, YARD, type PostFace, type PostYard } from '../src/data/postStations';
import { POSTS } from '../src/data/travel';
import { NPCS } from '../src/data/npcs';
import { plan } from '../src/world/sites';
import { generateChunk } from '../src/world/chunkgen';
import { B } from '../src/world/blocks';
import { heightAt, lakeDist, riverDist, roadDist, SEA } from '../src/world/terrain';

const P = plan();
const built: [number, number, number, number][] = [];
for (const s of P.sites) if (!s.id.startsWith('post-')) for (const r of s.rects) if (r[2] - r[0] < 70 && r[3] - r[1] < 70) built.push(r);
// (and where anyone stands: the townsfolk keep their spots)
for (const n of NPCS) for (const sl of n.schedule) built.push([Math.floor(sl.at[0]) - 1, Math.floor(sl.at[1]) - 1, Math.floor(sl.at[0]) + 2, Math.floor(sl.at[1]) + 2]);
const isBuilt = (x: number, z: number) => built.some((r) => x >= r[0] - 1 && x < r[2] + 1 && z >= r[1] - 1 && z < r[3] + 1);
// What's actually there once the world's built (a mill race or a village pond isn't in the terrain)
const chunks = new Map<string, Uint8Array>();
const block = (x: number, y: number, z: number) => { const k = (x >> 5) + ',' + (z >> 5); let c = chunks.get(k); if (!c) { c = generateChunk(x >> 5, z >> 5).data as Uint8Array; chunks.set(k, c); } return c[(x & 31) + 32 * ((z & 31) + 32 * y)]; };
const wet = (y: PostYard) => { for (let v = -7; v <= 4; v++) for (let u = -7; u <= 7; u++) { const [x, z] = yardAt(y, u, v); for (let h = y.base - 2; h <= y.base + 1; h++) if (block(x, h, z) === B.Water) return true; } return false; };
const FRONT: Record<PostFace, [number, number]> = { n: [0, -1], s: [0, 1], e: [1, 0], w: [-1, 0] };

const out: PostYard[] = [];
for (const post of POSTS) {
  // (Hollin Ford is the hand-built starting village, outside what the planner lays out: it keeps its sign)
  if (post.ferryFrom || post.id === 'hollin') continue;
  const found: { y: PostYard; score: number }[] = [];
  let best: { y: PostYard; score: number } | null = null;
  for (let r = 9; r <= 44; r += 1) for (let a = 0; a < 48; a++) {
    const t = (a / 48) * Math.PI * 2, x = Math.round(post.x + Math.sin(t) * r), z = Math.round(post.z + Math.cos(t) * r);
    for (const face of ['n', 's', 'e', 'w'] as PostFace[]) {
      const f = FRONT[face], tx = post.x - x, tz = post.z - z, l = Math.hypot(tx, tz);
      if ((tx * f[0] + tz * f[1]) / l < 0.55) continue; // its front toward the stop
      const y: PostYard = { post: post.id, x, z, face, base: 0 };
      let lo = Infinity, hi = -Infinity, ok = true;
      const hs: number[] = [];
      for (let v = YARD.v0; v <= YARD.v1 && ok; v++) for (let u = YARD.u0; u <= YARD.u1 && ok; u++) {
        const [cx, cz] = yardAt(y, u, v), h = heightAt(cx, cz);
        if (h <= SEA + 1 || isBuilt(cx, cz) || roadDist(cx + 0.5, cz + 0.5) < 3.2 || riverDist(cx + 0.5, cz + 0.5) < 7 || lakeDist(cx + 0.5, cz + 0.5) < 7) ok = false;
        lo = Math.min(lo, h); hi = Math.max(hi, h); hs.push(h);
      }
      if (!ok || hi - lo > 3) continue;
      hs.sort((p, q) => p - q);
      y.base = hs[hs.length >> 1];
      const score = r + (hi - lo) * 4;
      found.push({ y, score });
      if (!best || score < best.score) best = { y, score };
    }
    if (best && r > best.score + 2) break;
  }
  // The best that's dry
  best = found.sort((a, b) => a.score - b.score).find((f) => !wet(f.y)) ?? null;
  if (!best) { console.log(post.id, 'NO ROOM'); continue; }
  out.push(best.y);
  console.log(post.id, best.y.x, best.y.z, best.y.face, 'base', best.y.base, 'score', best.score);
}
writeFileSync('src/data/postYards.ts', `// Generated by scripts/poststations.ts (npm run -s poststations): each Charter Post stop's coaching yard.
import type { PostYard } from './postStations';

export const POST_YARDS: PostYard[] = [
${out.map((y) => `  ${JSON.stringify(y)},`).join('\n')}
];
`);
console.log('written', out.length);
