// The Charter's estates (src/data/estates.ts): small rows of building lots near each Charter Post town,
// side by side on flat, dry ground clear of every site, street, road and stream, their fronts on a
// shared lane and a track from the lane to the nearest road. Run it after moving a town or a road:
//   npx tsx scripts/estates.ts            (writes src/data/estates.ts; a few minutes)
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import { plan, inRects } from '../src/world/sites';
import { heightAt, roadDist, riverDist, lakeDist, landDist, WORLD_ROADS, SEA } from '../src/world/terrain';
import { POSTS } from '../src/data/travel';
import { WENDSIDE_LOTS as LOTS, LOT_W, LOT_D } from '../src/data/housing';

const HEAD = `// Generated by scripts/estates.ts: the Charter's estates, small rows of building lots near the Charter Post
// towns (data/housing.ts makes them lots). Each lot is [x0, z0, floor height]; door is the side its front
// faces (the lane's); lane runs along the fronts and track from the lane to the nearest road.
// Regenerate after moving a town or a road.

export interface Estate { id: string; name: string; town: string; door: 'n' | 's' | 'e' | 'w'; lane: [number, number][]; track: [number, number][]; lots: [number, number, number][] }
`;
// The estates are laid out over a world without them (their own lots would be in the way): empty the
// list, then run again in a fresh process that loads the world that way
if (!process.env.ESTATES_FRESH) {
  fs.writeFileSync('src/data/estates.ts', HEAD + '\nexport const ESTATES: Estate[] = [];\n');
  const r = spawnSync(process.execPath, [...process.execArgv, ...process.argv.slice(1)], { stdio: 'inherit', env: { ...process.env, ESTATES_FRESH: '1' } });
  process.exit(r.status ?? 1);
}

const P = plan();
const rects: [number, number, number, number][] = [];
for (const a of P.rectsByChunk.values()) rects.push(...a);
const W = LOT_W, D = LOT_D, GAP = 2;
type Door = 'n' | 's' | 'e' | 'w';
type Lot = { x0: number; z0: number; door: Door; base: number };
const taken: { x0: number; z0: number; x1: number; z1: number }[] = LOTS.map((l) => ({ x0: l.x0 - 4, z0: l.z0 - 4, x1: l.x0 + W + 4, z1: l.z0 + D + 4 }));
const hitsTaken = (x0: number, z0: number, x1: number, z1: number) => taken.some((t) => x0 < t.x1 && x1 > t.x0 && z0 < t.z1 && z1 > t.z0);

/** The ground's level for a lot here, or null: dry, no steeper than 4, clear of sites, streets, roads and water. */
function lotBase(x0: number, z0: number): number | null {
  let lo = 1e9, hi = -1e9, sum = 0, n = 0;
  for (let x = x0; x < x0 + W; x += 2) for (let z = z0; z < z0 + D; z += 2) {
    const h = heightAt(x, z);
    if (h <= SEA + 2) return null;
    lo = Math.min(lo, h); hi = Math.max(hi, h); sum += h; n++;
    if (hi - lo > 4) return null;
  }
  for (let x = x0 - 2; x <= x0 + W + 1; x += 3) for (let z = z0 - 2; z <= z0 + D + 1; z += 3) {
    if (roadDist(x, z) < 4 || riverDist(x, z) < 7 || lakeDist(x, z) < 7 || landDist(x, z) < 10) return null;
  }
  for (let x = x0 - 3; x <= x0 + W + 3; x += 3) for (let z = z0 - 3; z <= z0 + D + 3; z += 3) if (inRects(rects, x, z)) return null;
  return Math.round(sum / n);
}

/** The nearest point on any road. */
function nearRoad(x: number, z: number): [number, number, number] {
  let best: [number, number, number] = [Infinity, 0, 0];
  for (const r of WORLD_ROADS as [number, number][][]) for (let k = 0; k + 1 < r.length; k++) {
    const [ax, az] = r[k], [bx, bz] = r[k + 1], dx = bx - ax, dz = bz - az, L = dx * dx + dz * dz || 1;
    const t = Math.max(0, Math.min(1, ((x - ax) * dx + (z - az) * dz) / L)), px = ax + dx * t, pz = az + dz * t, d = Math.hypot(px - x, pz - z);
    if (d < best[0]) best = [d, px, pz];
  }
  return best;
}

/** A clear line for a track: no site, no water, not too steep. */
function trackOk(ax: number, az: number, bx: number, bz: number): boolean {
  const L = Math.hypot(bx - ax, bz - az);
  let prev = heightAt(ax, az);
  for (let s = 2; s < L - 3; s += 2) {
    const x = ax + ((bx - ax) * s) / L, z = az + ((bz - az) * s) / L, h = heightAt(x, z);
    if (inRects(rects, x, z, 1) || h <= SEA + 1 || riverDist(x, z) < 3 || Math.abs(h - prev) > 2) return false;
    prev = h;
  }
  return true;
}

type Estate = { lots: Lot[]; lane: [number, number][]; track: [number, number][]; d: number };
const towns = POSTS.filter((p) => !p.ferryFrom && !['hollin', 'temple'].includes(p.id));
const out: Record<string, Omit<Estate, 'd'>[]> = {};
for (const t of towns) {
  const tried: Estate[] = [];
  for (let r = 50; r <= 300; r += 8) for (let a = 0; a < Math.PI * 2; a += 8 / r) {
    const cx = t.x + Math.cos(a) * r, cz = t.z + Math.sin(a) * r;
    const [rd, rx, rz] = nearRoad(cx, cz);
    if (rd > 45 || rd < 12) continue;
    // The lots face the road: the door on the side toward it
    const vx = rx - cx, vz = rz - cz;
    const door: Door = Math.abs(vx) > Math.abs(vz) ? (vx > 0 ? 'e' : 'w') : (vz > 0 ? 's' : 'n');
    const along = door === 'n' || door === 's' ? [W + GAP, 0] : [0, D + GAP];
    const x00 = Math.round(cx - W / 2), z00 = Math.round(cz - D / 2);
    const row: Lot[] = [];
    for (let k = 0; k < 6; k++) {
      const x0 = x00 + along[0] * k, z0 = z00 + along[1] * k;
      if (hitsTaken(x0 - GAP, z0 - GAP, x0 + W + GAP, z0 + D + GAP)) break;
      const b = lotBase(x0, z0);
      if (b === null) break;
      if (row.length && Math.abs(b - row[0].base) > 3) break;
      row.push({ x0, z0, door, base: b });
    }
    if (row.length < 3) continue;
    // The lane along the fronts, a block and a half out, and a track from its middle to the road
    const first = row[0], last = row[row.length - 1];
    const lane: [number, number][] = door === 's' ? [[first.x0, first.z0 + D + 1.5], [last.x0 + W, first.z0 + D + 1.5]]
      : door === 'n' ? [[first.x0, first.z0 - 1.5], [last.x0 + W, first.z0 - 1.5]]
      : door === 'e' ? [[first.x0 + W + 1.5, first.z0], [first.x0 + W + 1.5, last.z0 + D]]
      : [[first.x0 - 1.5, first.z0], [first.x0 - 1.5, last.z0 + D]];
    const mx = (lane[0][0] + lane[1][0]) / 2, mz = (lane[0][1] + lane[1][1]) / 2;
    const [, tx, tz] = nearRoad(mx, mz);
    if (!trackOk(mx, mz, tx, tz)) continue;
    tried.push({ lots: row, lane, track: [[mx, mz], [tx, tz]], d: r });
  }
  // The longest rows, nearest first; two estates a town at most
  tried.sort((p, q) => q.lots.length - p.lots.length || p.d - q.d);
  const estates: Estate[] = [];
  for (const e of tried) {
    if (estates.length >= 2) break;
    const box = e.lots.map((l) => [l.x0 - 3, l.z0 - 3, l.x0 + W + 3, l.z0 + D + 3]);
    if (box.some(([a, b, c, d]) => hitsTaken(a, b, c, d))) continue;
    const ctr = (q: Estate) => [q.lots[0].x0 + (q.lots[q.lots.length - 1].x0 - q.lots[0].x0) / 2, q.lots[0].z0 + (q.lots[q.lots.length - 1].z0 - q.lots[0].z0) / 2];
    if (estates.some((q) => Math.hypot(ctr(q)[0] - ctr(e)[0], ctr(q)[1] - ctr(e)[1]) < 90)) continue;
    estates.push(e);
    for (const [a, b, c, d] of box) taken.push({ x0: a, z0: b, x1: c, z1: d });
  }
  out[t.id] = estates.map(({ lots, lane, track }) => ({ lots, lane, track }));
  console.log(`${t.id.padEnd(12)} ${estates.map((e) => `${e.lots.length}@${Math.round(e.d)}m door ${e.lots[0].door} base ${e.lots[0].base} at ${e.lots[0].x0},${e.lots[0].z0}`).join(' | ') || '-'}`);
}
